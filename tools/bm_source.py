# ---------------- בנייה ובדיקה ----------------
def build():
    units = []
    allw = {}
    want = ['75b:15', '75b:16'] + ['76a:%d' % i for i in range(1, 15)] + ['76b:%d' % i for i in range(1, 14)] + ['77a:1']
    words = []   # (vocalized token, seg) – רצף אחד לכל הסוגיא
    for s in want:
        for tok in seg(s).split():
            if key(tok): words.append((tok, s))
            else: words[-1] = (words[-1][0] + ' ' + tok, words[-1][1])
    pos = 0
    for u in U:
        lines = []
        for n, l in enumerate(u['lines'], 1):
            pk = [key(x) for x in l['p'].split() if key(x)]
            got = words[pos:pos + len(pk)]
            if [key(x[0]) for x in got] != pk:
                bad = next(i for i, (a, b) in enumerate(zip([key(x[0]) for x in got], pk)) if a != b) if len(got) == len(pk) else -1
                raise SystemExit(f'MISMATCH {u["id"]} line {n} at word {bad}: sefaria={[x[0] for x in got]} mine={pk}')
            pos += len(pk)
            nq = ' '.join(x[0] for x in got)
            segs = sorted(set(x[1] for x in got), key=lambda s: want.index(s))
            gl = []
            for a, m in l['w']:
                ak = [key(x) for x in a.split()]
                # הצורה המנוקדת מתוך השורה
                toks = [x[0] for x in got]; kk = [key(t) for t in toks]; voc = None; at = -1
                for i in range(len(kk) - len(ak) + 1):
                    if kk[i + 1:i + len(ak)] == ak[1:] and (kk[i] == ak[0] or re.fullmatch('[ודבלהמכש]{1,2}' + ak[0], kk[i])): voc = ' '.join(re.sub(r'[״׳"\'.,:;!?–]+', '', t).replace(' ', '') for t in toks[i:i + len(ak)]); at = i; break
                if voc is None and '...' not in a: raise SystemExit(f'GLOSS not in line {u["id"]} {n}: {a}')
                gl.append({'a': a, 'v': voc or a, 'm': m, 'i': at, 'k': len(ak)})
                allw.setdefault(a, {'a': a, 'v': voc or a, 'm': m, 'u': u['id']})
            rs = [{'ref': r, 'text': comm('rashi', r), 'x': RASHI_X.get(r, '')} for r in l['rs']]
            ts = [{'ref': r, 'text': comm('tosafot', r), 'x': TOS_X[r]} for r in l['ts']]
            for r in l['ts']:
                if r not in TOS_X: raise SystemExit('no TOS_X ' + r)
            lines.append({'n': n, 'niqqud': nq, 'toks': [x[0] for x in got], 'segs': segs, 'daf': segs[0].split(':')[0], 'pshat': l['t'], 'role': l['r'], 'rashi': rs, 'tosafot': ts, 'words': gl})
        useg = []
        for l in lines:
            for s in l['segs']:
                if s not in useg: useg.append(s)
        assert useg == u['segs'], (u['id'], useg, u['segs'])
        dafs = []
        for s in u['segs']:
            d = s.split(':')[0]
            if d not in dafs: dafs.append(d)
        units.append({'id': u['id'], 'title': u['title'], 'intro': u['intro'], 'segs': u['segs'], 'daf': ' – '.join(DAF(d) for d in dafs),
                      'lines': lines, 'flow': [{'type': a, 'who': b, 'text': c} for a, b, c in u['flow']], 'key': u['key']})
    if pos != len(words): raise SystemExit(f'{len(words) - pos} words left over: {[w[0] for w in words[pos:pos + 8]]}')
    for q in MC: assert len(q[1]) == 4 and q[4] in [u['id'] for u in U]
    return {
        'title': 'השוכר את האומנין · בבא מציעא ע"ו',
        'source': 'ספריא: William Davidson Edition – Vocalized Aramaic; רש"י ותוספות (מהדורת וילנא, ספריא); ביאור על פי שטיינזלץ ורש"י',
        'range': 'ע"ה ע"ב (המשנה) – ע"ו ע"א – ע"ו ע"ב (וסוף מימרת רבא בע"ז ע"א)',
        'units': units,
        'glossary': list(allw.values()),
        'concepts': [{'c': a, 'x': b} for a, b in CONCEPTS],
        'quiz': {
            'mc': [{'id': 'mc%d' % i, 'q': q, 'o': o, 'a': a, 'ex': ex, 'u': u} for i, (q, o, a, ex, u) in enumerate(MC, 1)],
            'who': [{'id': 'who%d' % i, 's': s, 'a': a, 'd': d} for i, (s, a, d) in enumerate(WHO, 1)],
            'order': ORDER,
            'shakla': [{'id': 'sh%d' % i, 'k': k, 'a': a, 'd': d} for i, (k, a, d) in enumerate(SHAKLA, 1)],
            'sevara': [{'id': 'sv%d' % i, 'q': q, 'pts': p, 'model': m} for i, (q, p, m) in enumerate(SEVARA, 1)],
            'tf': [{'id': 'tf%d' % i, 's': s, 'a': a, 'ex': ex} for i, (s, a, ex) in enumerate(TF, 1)],
        }}
if __name__ == '__main__':
    d = build()
